from __future__ import annotations

import hashlib
import json
import subprocess
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from .io import write_json
from .project import execution_identifier


def run_second_level_recalculation(
    project: dict[str, Any],
    run_dir: Path,
    run_id: str,
    sample_version: str,
    included_subject_ids: list[str],
    environment: dict[str, Any],
) -> dict[str, Any]:
    """Recompute only CONN second-level results for a frozen one-sample cohort."""
    if project.get("design", {}).get("type") != "one_sample":
        raise ValueError("Versioned recalculation currently supports one_sample designs")
    subject_ids = [str(item["id"]) for item in project.get("subjects", [])]
    included = set(map(str, included_subject_ids))
    unknown = sorted(included.difference(subject_ids))
    if unknown:
        raise ValueError(f"Unknown included subjects: {', '.join(unknown)}")
    if len(included) < 2:
        raise ValueError("At least two accepted subjects are required for this group analysis")

    physical_name = execution_identifier(project["project"]["name"])
    mask = [1 if subject_id in included else 0 for subject_id in subject_ids]
    version_key = sample_version.removeprefix("sha256:")[:16]
    folder_name = f"sample_{version_key}"
    task_dir = run_dir / "second_level_runs" / run_id
    task_dir.mkdir(parents=True, exist_ok=True)
    script_path = task_dir / "run_second_level.m"
    stdout_path = task_dir / "matlab_stdout.log"
    stderr_path = task_dir / "matlab_stderr.log"
    output_dir = run_dir / physical_name / "results" / "secondlevel" / folder_name
    sources = [str(item["conn_source"]) for item in project.get("seeds", [])]
    effect_name = f"Accepted_{version_key}"
    project_mat = run_dir / f"{physical_name}.mat"

    script_path.write_text(
        "\n".join(
            [
                "% Generated by CONN Pilot for a frozen accepted-subject sample.",
                "clear batch;",
                f"batch.filename = '{_matlab(project_mat.as_posix())}';",
                "batch.Results.name = 'SBC_01';",
                f"batch.Results.foldername = '{folder_name}';",
                "batch.Results.saveas = 'sample_mean';",
                f"batch.Results.between_subjects.effect_names = {{'{effect_name}'}};",
                f"batch.Results.between_subjects.effects = {{[{_vector(mask)}]}};",
                "batch.Results.between_subjects.contrast = 1;",
                "batch.Results.between_conditions.effect_names = {'rest'};",
                "batch.Results.between_conditions.contrast = 1;",
                f"batch.Results.between_sources.effect_names = {_cell(sources)};",
                f"batch.Results.between_sources.contrast = eye({len(sources)});",
                "batch.Results.display = 0;",
                "conn_batch(batch);",
                "",
            ]
        ),
        encoding="utf-8",
    )
    matlab = Path(environment["matlab"]["executable"])
    spm = Path(environment["spm"]["root"]).as_posix()
    conn = Path(environment["conn"]["root"]).as_posix()
    expression = (
        f"addpath('{_matlab(spm)}'); addpath('{_matlab(conn)}'); "
        f"run('{_matlab(script_path.as_posix())}');"
    )
    with stdout_path.open("w", encoding="utf-8") as stdout, stderr_path.open(
        "w", encoding="utf-8"
    ) as stderr:
        completed = subprocess.run(
            [str(matlab), "-batch", expression], stdout=stdout, stderr=stderr,
            text=True, env=_matlab_environment(environment),
        )
    if completed.returncode != 0:
        raise RuntimeError(f"MATLAB second-level recalculation exited with code {completed.returncode}")
    spm_models = sorted(output_dir.glob("**/SPM.mat")) if output_dir.is_dir() else []
    if not spm_models:
        raise RuntimeError("CONN did not create the expected versioned second-level SPM model")
    result_files = sorted(
        path for path in output_dir.glob("**/*")
        if path.is_file() and path.suffix.lower() in {".mat", ".nii", ".json"}
    )
    manifest = {
        "schema_version": "conn_pilot_second_level_run_v1",
        "created_at": datetime.now(timezone.utc).isoformat(),
        "second_level_run_id": run_id,
        "sample_version": sample_version,
        "included_subject_ids": [value for value in subject_ids if value in included],
        "excluded_subject_ids": [value for value in subject_ids if value not in included],
        "subject_mask": mask,
        "analysis": "SBC_01",
        "contrast": "sample_mean",
        "source_names": sources,
        "model_count": len(spm_models),
        "files": [
            {
                "relative_path": path.relative_to(output_dir).as_posix(),
                "bytes": path.stat().st_size,
                "sha256": _sha256(path),
            }
            for path in result_files
        ],
    }
    manifest_path = task_dir / "second_level_manifest.json"
    write_json(manifest_path, manifest)
    return {
        "manifest": manifest,
        "manifest_path": manifest_path,
        "script_path": script_path,
        "stdout_path": stdout_path,
        "stderr_path": stderr_path,
        "output_dir": output_dir,
        "artifact_paths": [manifest_path, script_path, stdout_path, stderr_path, *result_files],
    }


def _matlab(value: Any) -> str:
    return str(value).replace("\\", "/").replace("'", "''")


def _vector(values: list[int]) -> str:
    return " ".join(str(value) for value in values)


def _cell(values: list[str]) -> str:
    return "{" + ", ".join(f"'{_matlab(value)}'" for value in values) + "}"


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _matlab_environment(environment: dict[str, Any]) -> dict[str, str]:
    import os

    result = dict(os.environ)
    preferences = environment.get("matlab", {}).get("preferences_dir")
    if preferences:
        Path(preferences).mkdir(parents=True, exist_ok=True)
        result["MATLAB_PREFDIR"] = str(preferences)
    return result
