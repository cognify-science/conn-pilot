from __future__ import annotations

import hashlib
import json
import subprocess
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from .io import write_json
from .project import execution_identifier


def run_second_level_recalculation(
    project: dict[str, Any],
    run_dir: Path,
    run_id: str,
    sample_version: str,
    included_subject_ids: list[str],
    environment: dict[str, Any],
) -> dict[str, Any]:
    """Recompute CONN second-level contrasts for a frozen accepted-subject sample."""
    design = project.get("design", {})
    design_type = design.get("type")
    if design_type not in {"one_sample", "two_independent_groups"}:
        raise ValueError(f"Unsupported design for versioned recalculation: {design_type}")
    subject_ids = [str(item["id"]) for item in project.get("subjects", [])]
    included = set(map(str, included_subject_ids))
    unknown = sorted(included.difference(subject_ids))
    if unknown:
        raise ValueError(f"Unknown included subjects: {', '.join(unknown)}")
    if len(included) < 2:
        raise ValueError("At least two accepted subjects are required for this group analysis")

    groups = design.get("groups", {})
    if design_type == "two_independent_groups":
        empty_groups = [
            str(name) for name, members in groups.items()
            if not included.intersection(map(str, members))
        ]
        if empty_groups:
            raise ValueError(
                "Accepted sample must retain subjects in every group; empty: "
                + ", ".join(empty_groups)
            )

    physical_name = execution_identifier(project["project"]["name"])
    mask = [1 if subject_id in included else 0 for subject_id in subject_ids]
    version_key = sample_version.removeprefix("sha256:")[:16]
    folder_name = f"sample_{version_key}"
    task_dir = run_dir / "second_level_runs" / run_id
    task_dir.mkdir(parents=True, exist_ok=True)
    script_path = task_dir / "run_second_level.m"
    stdout_path = task_dir / "matlab_stdout.log"
    stderr_path = task_dir / "matlab_stderr.log"
    output_dir = run_dir / physical_name / "results" / "secondlevel" / folder_name
    sources = [str(item["conn_source"]) for item in project.get("seeds", [])]
    project_mat = run_dir / f"{physical_name}.mat"

    effect_vectors: dict[str, list[float]] = {
        "AllSubjects": [1.0 if subject_id in included else 0.0 for subject_id in subject_ids]
    }
    for name, members in groups.items():
        member_set = set(map(str, members))
        effect_vectors[str(name)] = [
            1.0 if subject_id in included and subject_id in member_set else 0.0
            for subject_id in subject_ids
        ]
    for name, values in design.get("covariates", {}).items():
        effect_vectors[str(name)] = [
            float(values[subject_id]) if subject_id in included else 0.0
            for subject_id in subject_ids
        ]
    contrasts = design.get("contrasts", [])
    if not contrasts:
        raise ValueError("Project design has no second-level contrasts")

    lines = [
        "% Generated by CONN Pilot for a frozen accepted-subject sample.",
        f"project_file = '{_matlab(project_mat.as_posix())}';",
    ]
    for index, contrast in enumerate(contrasts, start=1):
        names = list(map(str, contrast["effects"]))
        missing = [name for name in names if name not in effect_vectors]
        if missing:
            raise ValueError("Contrast references unavailable effects: " + ", ".join(missing))
        contrast_folder = f"{folder_name}/{_safe_identifier(str(contrast['name']))}"
        lines.extend(
            [
                f"clear results_batch_{index};",
                f"results_batch_{index}.filename = project_file;",
                f"results_batch_{index}.Results.name = 'SBC_01';",
                f"results_batch_{index}.Results.foldername = '{_matlab(contrast_folder)}';",
                f"results_batch_{index}.Results.saveas = '{_matlab(_safe_identifier(str(contrast['name'])))}';",
                f"results_batch_{index}.Results.between_subjects.effect_names = {_cell(names)};",
                f"results_batch_{index}.Results.between_subjects.effects = "
                + "{" + ", ".join(f"[{_vector(effect_vectors[name])}]" for name in names) + "};",
                f"results_batch_{index}.Results.between_subjects.contrast = [{_vector(contrast['weights'])}];",
                f"results_batch_{index}.Results.between_conditions.effect_names = {{'rest'}};",
                f"results_batch_{index}.Results.between_conditions.contrast = 1;",
                f"results_batch_{index}.Results.between_sources.effect_names = {_cell(sources)};",
                f"results_batch_{index}.Results.between_sources.contrast = eye({len(sources)});",
                f"results_batch_{index}.Results.display = 0;",
                f"conn_batch(results_batch_{index});",
                "",
            ]
        )

    script_path.write_text(
        "\n".join(lines),
        encoding="utf-8",
    )
    matlab = Path(environment["matlab"]["executable"])
    spm = Path(environment["spm"]["root"]).as_posix()
    conn = Path(environment["conn"]["root"]).as_posix()
    expression = (
        f"addpath('{_matlab(spm)}'); addpath('{_matlab(conn)}'); "
        f"run('{_matlab(script_path.as_posix())}');"
    )
    with stdout_path.open("w", encoding="utf-8") as stdout, stderr_path.open(
        "w", encoding="utf-8"
    ) as stderr:
        completed = subprocess.run(
            [str(matlab), "-batch", expression], stdout=stdout, stderr=stderr,
            text=True, env=_matlab_environment(environment),
        )
    if completed.returncode != 0:
        raise RuntimeError(f"MATLAB second-level recalculation exited with code {completed.returncode}")
    spm_models = sorted(output_dir.glob("**/SPM.mat")) if output_dir.is_dir() else []
    if not spm_models:
        raise RuntimeError("CONN did not create the expected versioned second-level SPM model")
    result_files = sorted(
        path for path in output_dir.glob("**/*")
        if path.is_file() and path.suffix.lower() in {".mat", ".nii", ".json"}
    )
    manifest = {
        "schema_version": "conn_pilot_second_level_run_v2",
        "created_at": datetime.now(timezone.utc).isoformat(),
        "second_level_run_id": run_id,
        "sample_version": sample_version,
        "included_subject_ids": [value for value in subject_ids if value in included],
        "excluded_subject_ids": [value for value in subject_ids if value not in included],
        "subject_mask": mask,
        "design_type": design_type,
        "analysis": "SBC_01",
        "contrasts": [
            {
                "name": str(contrast["name"]),
                "effects": list(map(str, contrast["effects"])),
                "weights": list(contrast["weights"]),
            }
            for contrast in contrasts
        ],
        "effect_vectors": effect_vectors,
        "source_names": sources,
        "model_count": len(spm_models),
        "files": [
            {
                "relative_path": path.relative_to(output_dir).as_posix(),
                "bytes": path.stat().st_size,
                "sha256": _sha256(path),
            }
            for path in result_files
        ],
    }
    manifest_path = task_dir / "second_level_manifest.json"
    write_json(manifest_path, manifest)
    return {
        "manifest": manifest,
        "manifest_path": manifest_path,
        "script_path": script_path,
        "stdout_path": stdout_path,
        "stderr_path": stderr_path,
        "output_dir": output_dir,
        "artifact_paths": [manifest_path, script_path, stdout_path, stderr_path, *result_files],
    }


def _matlab(value: Any) -> str:
    return str(value).replace("\\", "/").replace("'", "''")


def _vector(values: list[int | float]) -> str:
    return " ".join(str(value) for value in values)


def _cell(values: list[str]) -> str:
    return "{" + ", ".join(f"'{_matlab(value)}'" for value in values) + "}"


def _safe_identifier(value: str) -> str:
    import re

    return re.sub(r"[^A-Za-z0-9_-]+", "_", value).strip("_") or "contrast"


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _matlab_environment(environment: dict[str, Any]) -> dict[str, str]:
    import os

    result = dict(os.environ)
    preferences = environment.get("matlab", {}).get("preferences_dir")
    if preferences:
        Path(preferences).mkdir(parents=True, exist_ok=True)
        result["MATLAB_PREFDIR"] = str(preferences)
    return result
